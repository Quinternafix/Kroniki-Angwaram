/* =========================================================
   AKTUALNY JĘZYK
========================================================= */

let currentLanguage =
    localStorage.getItem("language") || "pl";


/* =========================================================
   GET LANGUAGE
========================================================= */

export function getLanguage() {

    return currentLanguage;

}


/* =========================================================
   TŁUMACZENIE KLUCZA
========================================================= */

export function t(key) {

    return (
        translations[currentLanguage]?.[key] ??
        translations.pl?.[key] ??
        key
    );

}


/* =========================================================
   LOCALIZE
========================================================= */

export function localize(item, field) {

    if (
        !item ||
        typeof item !== "object"
    ) {

        return "";
    }


    const language =
        currentLanguage;

    const fallbackLanguage =
        "pl";


    /* -----------------------------------------
       1. Format:
       translations: {
           en: {
               race: "Half-dragon"
           }
       }
    ----------------------------------------- */

    const translated =
        item.translations
            ?.[language]
            ?.[field];


    if (
        translated !== undefined &&
        translated !== null &&
        translated !== ""
    ) {

        return translated;
    }


    /* -----------------------------------------
       2. Polski fallback
    ----------------------------------------- */

    const translatedPl =
        item.translations
            ?.[fallbackLanguage]
            ?.[field];


    if (
        translatedPl !== undefined &&
        translatedPl !== null &&
        translatedPl !== ""
    ) {

        return translatedPl;
    }


    /* -----------------------------------------
       3. Pole jako obiekt językowy
    ----------------------------------------- */

    const value =
        item[field];


    if (
        value &&
        typeof value === "object" &&
        !Array.isArray(value)
    ) {

        const localizedValue =
            value[language];


        if (
            localizedValue !== undefined &&
            localizedValue !== null &&
            localizedValue !== ""
        ) {

            return localizedValue;
        }


        const polishValue =
            value[fallbackLanguage];


        if (
            polishValue !== undefined &&
            polishValue !== null &&
            polishValue !== ""
        ) {

            return polishValue;
        }


        const englishValue =
            value.en;


        if (
            englishValue !== undefined &&
            englishValue !== null &&
            englishValue !== ""
        ) {

            return englishValue;
        }


        const spanishValue =
            value.es;


        if (
            spanishValue !== undefined &&
            spanishValue !== null &&
            spanishValue !== ""
        ) {

            return spanishValue;
        }

    }


    /* -----------------------------------------
       4. Zwykła wartość
    ----------------------------------------- */

    if (
        value !== undefined &&
        value !== null &&
        value !== ""
    ) {

        return String(value);
    }


    return "";

}


/* =========================================================
   LOCALIZE VALUE
========================================================= */

export function localizeValue(value) {

    if (
        value === undefined ||
        value === null
    ) {

        return "";
    }


    if (
        typeof value === "object" &&
        !Array.isArray(value)
    ) {

        return (
            value[currentLanguage] ??
            value.pl ??
            value.en ??
            value.es ??
            ""
        );

    }


    return String(value);

}


/* =========================================================
   APPLY TRANSLATIONS
========================================================= */

export function applyTranslations() {

    document.documentElement.lang =
        currentLanguage;


    document.title =
        t("site.title");


    document
        .querySelectorAll("[data-i18n]")
        .forEach(element => {

            element.textContent =
                t(element.dataset.i18n);

        });


    document
        .querySelectorAll("[data-i18n-placeholder]")
        .forEach(element => {

            element.placeholder =
                t(
                    element.dataset
                        .i18nPlaceholder
                );

        });


    document
        .querySelectorAll("[data-language]")
        .forEach(button => {

            button.setAttribute(
                "aria-pressed",
                String(
                    button.dataset.language ===
                    currentLanguage
                )
            );

        });

}


/* =========================================================
   SET LANGUAGE
========================================================= */

export function setLanguage(language) {

    if (
        !translations[language]
    ) {

        return;
    }


    if (
        language === currentLanguage
    ) {

        return;
    }


    currentLanguage =
        language;


    localStorage.setItem(
        "language",
        language
    );


    applyTranslations();


    window.dispatchEvent(
        new Event("languagechange")
    );

}


/* =========================================================
   INIT I18N
========================================================= */

let initialized = false;


export function initI18n() {

    if (initialized) {

        applyTranslations();

        return;
    }


    initialized = true;


    document.addEventListener(
        "click",
        event => {

            const button =
                event.target.closest(
                    "[data-language]"
                );


            if (!button) {

                return;
            }


            setLanguage(
                button.dataset.language
            );

        }
    );


    applyTranslations();

}
